#!/usr/bin/env bash

# Blinding + fail-closed leak detection for the benchmark's judging stage
# (plan section "Judging", step 3). Sourceable by judge-matrix.sh; also
# runnable as `bash sanitize.sh --self-test`.
#
# The judge must not be able to tell WHICH condition produced a document, so
# sanitize_doc removes every process artifact the pipeline leaves behind, and
# leak_check then refuses to pass anything that still names a vendor or a
# benchmark mechanism. leak_check is the gate, not sanitize_doc: a pair whose
# document still trips it is recorded `sanitize-leak` and never judged.

if [[ -n "${BENCH_SANITIZE_SOURCED:-}" ]]; then
  return 0 2>/dev/null || true
fi
BENCH_SANITIZE_SOURCED=1

shopt -u patsub_replacement 2>/dev/null || true

BENCH_SANITIZE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BENCH_SANITIZE_REPO_ROOT="$(cd "$BENCH_SANITIZE_DIR/../.." && pwd)"

# strip_human_summary (lib/co-evolution.sh:1279) keys on the LAST `## HUMAN
# SUMMARY` heading, which is the behavior we want: a body that merely mentions
# the heading is preserved, only the agent-appended trailer is dropped.
if ! declare -F strip_human_summary >/dev/null 2>&1; then
  # shellcheck source=../../lib/co-evolution.sh
  source "$BENCH_SANITIZE_REPO_ROOT/lib/co-evolution.sh"
fi

# Lines below this many non-blank lines after the last `---` rule count as a
# footer worth stripping; anything larger is document content, not a trailer.
: "${BENCH_FOOTER_MAX_LINES:=10}"

# sanitize_doc IN OUT — write a blinded copy of IN to OUT.
#
# 1. normalize CRLF (Windows-authored finals otherwise leak \r into judging)
# 2. strip [CONTESTED…] / [CLARIFY…] markers  (evals/judge-bounce.sh:91, widened
#    to the bracket-payload form handled by strip_protocol_markers in lib)
# 3. strip the HUMAN SUMMARY trailer          (strip_human_summary)
# 4. drop provenance lines                    (evals/judge-bounce.sh:97 pattern)
# 5. drop benchmark tells                     (STUCK banner, pass/panel/critique
#                                              language, "Reviewer N" labels)
# 6. normalize the first H1 to `# Plan`       (title style is a condition tell)
# 7. collapse runs of 2+ blank lines to one (uniform: provenance-line removal
#    leaves 2-blank gaps only in bounced docs — a condition-correlated tell)
# 8. drop a trailing `---`-delimited footer
sanitize_doc() {
  local in_file="${1:?sanitize_doc requires an input file}"
  local out_file="${2:?sanitize_doc requires an output file}"
  local work

  [[ -f "$in_file" ]] || die "sanitize_doc: input not found: $in_file"

  work=$(mktemp -d -t bench-sanitize-XXXXXX) || die "sanitize_doc: could not create a work dir"

  sed -e 's/\r$//' \
      -e 's/\[CONTESTED[^]]*\]//g' \
      -e 's/\[CLARIFY[^]]*\]//g' \
      "$in_file" > "$work/markers.md"

  strip_human_summary "$work/markers.md" "$work/nohs.md"

  # `|| true` mirrors judge-bounce.sh:98 — grep exits 1 on a document that ends
  # up with no surviving lines, which is not an error here.
  grep -viE '^(generated by|produced by|co-evolve|agent-bouncer|pass [0-9]+ of)' "$work/nohs.md" \
    | grep -viE 'CO-EVOLVE:STUCK|NOT-final|NOT A CLEAN FINAL|bounce pass|panel critique|synthesized from|Reviewer [0-9]' \
    > "$work/lines.md" || true

  awk -v footer_max="${BENCH_FOOTER_MAX_LINES}" '
    { lines[NR] = $0 }
    END {
      total = NR

      # 8. Trailing `---` footer: find the last horizontal rule, and cut from it
      # when what follows is small enough to be a trailer rather than a section.
      cut = 0
      for (i = total; i > 1; i--) {
        if (lines[i] ~ /^-{3,}[[:space:]]*$/) {
          nonblank = 0
          for (j = i + 1; j <= total; j++) {
            if (lines[j] ~ /[^[:space:]]/) nonblank++
          }
          if (nonblank <= footer_max) cut = i
          break
        }
      }
      if (cut > 0) total = cut - 1

      # 6 + 7 in one pass: first H1 becomes `# Plan`; any run of 2 or more
      # blank lines collapses to a single blank line.
      h1_done = 0
      blanks = 0
      for (i = 1; i <= total; i++) {
        line = lines[i]
        if (line ~ /^[[:space:]]*$/) { blanks++; continue }
        if (blanks > 0) {
          emit = (blanks >= 2) ? 1 : blanks
          for (k = 0; k < emit; k++) print ""
          blanks = 0
        }
        if (!h1_done && line ~ /^#[[:space:]]/) {
          print "# Plan"
          h1_done = 1
          continue
        }
        print line
      }
    }
  ' "$work/lines.md" > "$out_file"

  rm -rf -- "$work"
}

# leak_check FILE BANNED_FILE — print every line of FILE containing a banned
# token (case-insensitive substring), one report line per token per hit.
# Returns 1 when anything leaked, 0 on a clean document.
#
# Matching is done in pure bash on lowercased strings rather than `grep -iF`:
# GNU grep 3.0 as shipped with Git Bash ABORTS (SIGABRT) on `-iF` with a
# multi-word pattern, which would turn this fail-closed gate into a silent pass.
leak_check() {
  local file="${1:?leak_check requires a file}"
  local banned_file="${2:?leak_check requires a banned-token file}"
  local token
  local -i ntokens=0

  [[ -f "$file" ]] || die "leak_check: file not found: $file"
  [[ -f "$banned_file" ]] || die "leak_check: banned-token file not found: $banned_file"

  while IFS= read -r token; do
    token="${token%$'\r'}"
    token="${token%"${token##*[![:space:]]}"}"
    [[ -z "$token" ]] && continue
    [[ "$token" == \#* ]] && continue
    ntokens+=1
  done < "$banned_file"

  if (( ntokens == 0 )); then
    die "leak_check: $banned_file lists no tokens — refusing to certify a document against an empty list"
  fi

  # Single awk pass: one process total regardless of document or list size.
  # The earlier per-(line x token) shell loop forked tr for every pair and
  # cost ~2s per document line — a full batch would have spent an hour here
  # before the first judge call.
  awk '
    FNR == NR {
      sub(/\r$/, ""); sub(/[[:space:]]+$/, "")
      if ($0 == "" || $0 ~ /^#/) next
      orig[++n] = $0; lc[n] = tolower($0)
      next
    }
    {
      sub(/\r$/, "")
      low = tolower($0)
      for (i = 1; i <= n; i++)
        if (index(low, lc[i])) { printf "%s: line %d: %s\n", orig[i], FNR, $0; hits++ }
    }
    END { exit hits > 0 ? 1 : 0 }
  ' "$banned_file" "$file"
}

# --- Self-test ---------------------------------------------------------------
# `bash sanitize.sh --self-test` — tmp files only, no LLM calls, no network.

_sanitize_selftest() {
  local failures=0
  local work
  work=$(mktemp -d -t bench-sanitize-selftest-XXXXXX) || { echo "FAIL: mktemp"; return 1; }
  trap 'rm -rf -- "$work"' RETURN

  _check() {
    local name="$1" expected="$2" actual="$3"
    [[ "$expected" == "$actual" ]] && return 0
    printf 'FAIL: %s\n  expected: %s\n  actual:   %s\n' "$name" "$expected" "$actual"
    failures=$((failures + 1))
  }

  cat > "$work/final.md" <<'DOC'
# Migration Plan for the Billing Service

Generated by claude-opus-4-8 via co-evolve-bouncer.sh.
co-evolve pass 2 of 2.

Step one: freeze writes. [CONTESTED] The reviewer preferred a read replica.



Step two: backfill. [CLARIFY] Does this include archived rows?

Reviewer 2 argued for a longer window.
This plan was synthesized from three critiques.

## HUMAN SUMMARY

- pass 1: tightened the rollback section

---

Produced by agent-bouncer, pass 2 of 2.
DOC

  sanitize_doc "$work/final.md" "$work/clean.md"
  local clean
  clean=$(cat "$work/clean.md")

  _check "first H1 normalized" "# Plan" "$(head -1 "$work/clean.md")"

  local pattern
  for pattern in 'CONTESTED' 'CLARIFY' 'Generated by' 'co-evolve' 'HUMAN SUMMARY' \
                 'Reviewer 2' 'synthesized from' 'agent-bouncer' 'Migration Plan'; do
    if printf '%s' "$clean" | grep -qF -- "$pattern"; then
      printf 'FAIL: sanitize_doc left %s in the output\n' "$pattern"
      failures=$((failures + 1))
    fi
  done

  for pattern in 'freeze writes' 'backfill'; do
    if ! printf '%s' "$clean" | grep -qF -- "$pattern"; then
      printf 'FAIL: sanitize_doc dropped body content (%s)\n' "$pattern"
      failures=$((failures + 1))
    fi
  done

  # Any run of 2+ blank lines must collapse to one (2-blank gaps from deleted
  # provenance lines are a condition-correlated tell), so assert on 2+.
  local max_blank_run
  max_blank_run=$(awk '
    /^[[:space:]]*$/ { run++; if (run > max) max = run; next }
    { run = 0 }
    END { print max + 0 }
  ' "$work/clean.md")
  if (( max_blank_run >= 2 )); then
    printf 'FAIL: sanitize_doc left a blank-line run of %s\n' "$max_blank_run"
    failures=$((failures + 1))
  fi

  # Trailing `---` footer removed.
  if printf '%s' "$clean" | grep -qF -- '---'; then
    printf 'FAIL: sanitize_doc left the trailing --- footer\n'
    failures=$((failures + 1))
  fi

  # A `---` with a LARGE tail is a section rule, not a footer: keep it.
  {
    printf '# Plan\n\nIntro.\n\n---\n\n'
    local i
    for i in $(seq 1 15); do printf 'Body line %s.\n' "$i"; done
  } > "$work/rule.md"
  sanitize_doc "$work/rule.md" "$work/rule-clean.md"
  grep -qF 'Body line 15.' "$work/rule-clean.md" || {
    printf 'FAIL: sanitize_doc cut a document section as if it were a footer\n'
    failures=$((failures + 1)); }

  # leak_check: hit path
  printf '# comment\ncodex\nbounce pass\nHUMAN SUMMARY\n' > "$work/banned.txt"
  printf '# Plan\n\nWe asked CODEX to review the rollback.\nA clean second line.\n' > "$work/leaky.md"
  local leak_out leak_rc=0
  leak_out=$(leak_check "$work/leaky.md" "$work/banned.txt") || leak_rc=$?
  _check "leak_check returns 1 on a hit" "1" "$leak_rc"
  printf '%s' "$leak_out" | grep -qF 'codex: line 3:' || {
    printf 'FAIL: leak_check did not report the offending line\n  got: %s\n' "$leak_out"
    failures=$((failures + 1)); }
  _check "leak_check reports one line per hit" "1" "$(printf '%s\n' "$leak_out" | grep -c 'line ')"

  # leak_check: multi-word token (the -iF abort case) must still be caught
  printf '# Plan\n\nThe second Bounce Pass tightened it.\n' > "$work/leaky2.md"
  leak_rc=0
  leak_out=$(leak_check "$work/leaky2.md" "$work/banned.txt") || leak_rc=$?
  _check "leak_check catches a multi-word token" "1" "$leak_rc"
  printf '%s' "$leak_out" | grep -qF 'bounce pass: line 3:' || {
    printf 'FAIL: leak_check missed the multi-word token\n  got: %s\n' "$leak_out"
    failures=$((failures + 1)); }

  # leak_check: clean path
  printf '# Plan\n\nFreeze writes, then backfill in batches.\n' > "$work/clean-doc.md"
  leak_rc=0
  leak_out=$(leak_check "$work/clean-doc.md" "$work/banned.txt") || leak_rc=$?
  _check "leak_check returns 0 when clean" "0" "$leak_rc"
  _check "leak_check prints nothing when clean" "" "$leak_out"

  # End to end: the sanitized fixture must survive its own banned list.
  leak_rc=0
  leak_out=$(leak_check "$work/clean.md" "$work/banned.txt") || leak_rc=$?
  _check "sanitized fixture passes leak_check" "0" "$leak_rc"

  if (( failures == 0 )); then
    echo "sanitize.sh self-test: PASS"
    return 0
  fi
  echo "sanitize.sh self-test: $failures FAILURE(S)"
  return 1
}

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
  case "${1:-}" in
    --self-test) _sanitize_selftest ;;
    *) echo "usage: bash sanitize.sh --self-test   (this file is normally sourced)" >&2; exit 2 ;;
  esac
fi

#!/usr/bin/env bash
# evals/lib/judge-lib.sh
# Shared blind-judging internals, extracted verbatim from evals/judge-bounce.sh
# so that harnesses which judge OTHER document pairs (benchmarks/judge-matrix.sh)
# reuse the same blinding, trial loop, and evidence verification rather than
# re-implementing them and drifting.
#
# Sourced by: evals/judge-bounce.sh, benchmarks/judge-matrix.sh.
#
# NOTE: no `set -euo pipefail` here — this file is SOURCED; callers set strictness.
#
# Requires from the caller's environment (source lib/co-evolution.sh first):
#   log(), file_contains_auth_failure(), and jq on PATH.
#
# Public API:
#   judge_blind <file>                        -- prints the blinded document on stdout
#   judge_build_trial_prompt <a> <b> <out>    -- writes the A/B judging prompt
#   judge_invoke_trial <prompt_file> <out>    -- runs the judge CLI, parses/retries, writes verdict JSON
#   judge_run_trial <a> <b> <out>             -- build prompt + invoke (one blind trial)
#   judge_norm <file>                         -- prints the whitespace-normalized document
#   judge_reset_evidence_state                -- resets the evidence accumulator globals
#   judge_check_trial_evidence <trial> <normA> <normB> <trial-no>
#
# GLOBALS (kept under their original judge-bounce.sh names on purpose — the
# extraction is behavior-preserving, and array-valued JUDGE_ARGS cannot be
# passed as a plain parameter):
#   IN  WORK        -- caller-owned scratch dir; trial prompt/raw/stderr files land here
#   IN  JUDGE_CMD   -- judge CLI executable name
#   IN  JUDGE_ARGS  -- array of extra CLI flags (may be unset/empty)
#   OUT EVIDENCE_OK EVIDENCE_TOTAL EVIDENCE_FAILED VERIFIED_EVIDENCE
#                   -- accumulated by judge_check_trial_evidence across trials;
#                      initialize with judge_reset_evidence_state before the
#                      first call.

# --- Blinding: strip markers, HUMAN SUMMARY blocks, provenance ----------------
judge_blind() {
  sed -e 's/\[CONTESTED\]//g' -e 's/\[CLARIFY\]//g' "$1" \
    | awk '
        /^#+[ \t]*HUMAN SUMMARY/ { in_hs = 1; next }
        in_hs && /^#/ { in_hs = 0 }
        !in_hs { print }
      ' \
    | grep -viE '^(generated by|produced by|co-evolve|agent-bouncer|pass [0-9]+ of)' \
    || true
}

# --- Trial prompt --------------------------------------------------------------
# $1 = file shown as Document A, $2 = file shown as Document B, $3 = out prompt file
judge_build_trial_prompt() {
  local doc_a="$1" doc_b="$2" prompt_file="$3"

  cat > "$prompt_file" <<PROMPT
You are evaluating two anonymous versions of the same document. You do not
know which is older. Judge which version is BETTER as a document: clearer,
more complete, better-argued, more actionable — not merely longer or shorter.

Respond with ONLY a JSON object, no markdown fences, no commentary:
{
  "better": "A" | "B" | "tie",
  "confidence": "low" | "medium" | "high",
  "reasons": ["<short reason>", ...],
  "evidence": [
    {"doc": "A" | "B", "quote": "<verbatim quote of 5-25 words from that document supporting your judgment>"}
  ]
}
Rules: 1-3 reasons; 1-3 evidence entries; every quote must be copied
verbatim from the named document.

## Document A

$(cat "$doc_a")

## Document B

$(cat "$doc_b")
PROMPT
}

# --- Judge CLI invocation + parse/retry -----------------------------------------
# $1 = prompt file, $2 = out json. Returns 1 when no verdict could be parsed.
judge_invoke_trial() {
  local prompt_file="$1" out="$2"
  local raw_file="$WORK/trial-raw.txt"

  local attempt
  for attempt in 1 2; do
    : > "$raw_file"
    "$JUDGE_CMD" -p --output-format text ${JUDGE_ARGS[@]+"${JUDGE_ARGS[@]}"} < "$prompt_file" > "$raw_file" 2>"$WORK/trial-stderr.log" || true
    # Auth failures are not retryable and not "unparseable" — name the fix.
    if file_contains_auth_failure "$raw_file" || file_contains_auth_failure "$WORK/trial-stderr.log"; then
      log "ERROR: judge CLI '$JUDGE_CMD' is not authenticated — run \`$JUDGE_CMD\` interactively to log in, then re-run."
      return 1
    fi
    # Accept raw JSON or JSON wrapped in a fence.
    if jq -e '.better and .confidence' "$raw_file" >/dev/null 2>&1; then
      cp "$raw_file" "$out"; return 0
    fi
    sed -n '/^{/,/^}/p' "$raw_file" > "$WORK/trial-extract.json" || true
    if jq -e '.better and .confidence' "$WORK/trial-extract.json" >/dev/null 2>&1; then
      cp "$WORK/trial-extract.json" "$out"; return 0
    fi
    log "WARNING: judge returned unparseable output (attempt $attempt)"
  done
  return 1
}

# --- One blind trial ------------------------------------------------------------
# $1 = file shown as Document A, $2 = file shown as Document B, $3 = out json
judge_run_trial() {
  local doc_a="$1" doc_b="$2" out="$3"
  local prompt_file="$WORK/trial-prompt.md"

  judge_build_trial_prompt "$doc_a" "$doc_b" "$prompt_file"
  judge_invoke_trial "$prompt_file" "$out"
}

# --- Evidence verification (hallucination check) --------------------------------
# Each quote must appear in the document it cites (whitespace-normalized
# substring). Fabricated evidence invalidates the verdict.
judge_norm() { tr -s '[:space:]' ' ' < "$1" | tr -d '\r'; }

judge_reset_evidence_state() {
  EVIDENCE_OK=true
  EVIDENCE_TOTAL=0
  EVIDENCE_FAILED=0
  VERIFIED_EVIDENCE="[]"
}

judge_check_trial_evidence() { # $1=trial-file $2=normA $3=normB $4=trial-no
  local n
  n=$(jq '.evidence | length' "$1" 2>/dev/null || echo 0)
  local k
  for (( k=0; k<n; k++ )); do
    local doc quote hay found
    doc=$(jq -r ".evidence[$k].doc" "$1")
    # Trim after whitespace-normalization: real judges quote up to a clause
    # boundary, and a trailing space where the document continues with
    # punctuation ("…exclusive " vs "…exclusive.") is a transcription
    # artifact, not fabrication. First live batch failed 6/7 verdicts on
    # exactly this.
    quote=$(jq -r ".evidence[$k].quote" "$1" | tr -s '[:space:]' ' ' | sed 's/^ *//; s/ *$//')
    [[ "$doc" == "A" ]] && hay="$2" || hay="$3"
    found=false
    if [[ -n "$quote" ]] && printf '%s' "$hay" | grep -qF "$quote"; then
      found=true
    elif (( ${#quote} > 60 )) && printf '%s' "$hay" | grep -qF "${quote:0:60}"; then
      # Tail-truncation tolerance: a 60-char verbatim prefix is not something
      # a hallucinated quote produces by accident.
      found=true
    fi
    EVIDENCE_TOTAL=$((EVIDENCE_TOTAL + 1))
    if [[ "$found" == false ]]; then
      EVIDENCE_FAILED=$((EVIDENCE_FAILED + 1))
      EVIDENCE_OK=false
    fi
    VERIFIED_EVIDENCE=$(printf '%s' "$VERIFIED_EVIDENCE" | jq \
      --argjson trial "$4" --arg doc "$doc" --arg quote "$quote" --argjson ok "$found" \
      '. += [{trial: $trial, doc: $doc, quote: $quote, verified: $ok}]')
  done
}
